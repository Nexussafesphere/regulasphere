import { Document, Page, Text, View, StyleSheet, renderToBuffer } from "@react-pdf/renderer";

export interface ReportPdfData {
  businessName: string;
  sector: string;
  reportDate: string;
  reportType: string;
  overallScore: number;
  riskLevel?: string;
  summary: string;
  recommendations: string[];
  totalObligations: number;
  completedObligations: number;
  overdueObligations: number;
}

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 11, fontFamily: "Helvetica", color: "#1A2238" },
  header: { marginBottom: 20, borderBottom: "2pt solid #D4AF37", paddingBottom: 12 },
  title: { fontSize: 20, fontWeight: 700, marginBottom: 4 },
  subtitle: { fontSize: 10, color: "#6B7280" },
  scoreBlock: { flexDirection: "row", justifyContent: "space-between", marginVertical: 16 },
  scoreBox: { alignItems: "center", padding: 12, border: "1pt solid #E8EAEE", borderRadius: 6, width: "23%" },
  scoreLabel: { fontSize: 8, color: "#6B7280", marginTop: 4, textAlign: "center" },
  scoreValue: { fontSize: 18, fontWeight: 700 },
  sectionTitle: { fontSize: 13, fontWeight: 700, marginTop: 20, marginBottom: 8, color: "#1A2238" },
  paragraph: { fontSize: 10, lineHeight: 1.5, color: "#374151" },
  bullet: { flexDirection: "row", marginBottom: 6 },
  bulletDot: { width: 10, fontSize: 10 },
  bulletText: { flex: 1, fontSize: 10, lineHeight: 1.4, color: "#374151" },
  footer: {
    position: "absolute", bottom: 30, left: 40, right: 40, fontSize: 8,
    color: "#9CA3AF", textAlign: "center", borderTop: "0.5pt solid #E8EAEE", paddingTop: 8,
  },
});

function scoreColor(score: number): string {
  if (score >= 80) return "#059669";
  if (score >= 60) return "#D97706";
  return "#DC2626";
}

export async function generateReportPdf(data: ReportPdfData): Promise<Buffer> {
  const doc = (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.title}>RegulaSphere Compliance Report</Text>
          <Text style={styles.subtitle}>{data.businessName} — {data.sector} Sector</Text>
          <Text style={styles.subtitle}>{data.reportType} | Generated {data.reportDate}</Text>
        </View>

        <View style={styles.scoreBlock}>
          <View style={styles.scoreBox}>
            <Text style={[styles.scoreValue, { color: scoreColor(data.overallScore) }]}>
              {data.overallScore}%
            </Text>
            <Text style={styles.scoreLabel}>Compliance Score</Text>
          </View>
          <View style={styles.scoreBox}>
            <Text style={styles.scoreValue}>{data.totalObligations}</Text>
            <Text style={styles.scoreLabel}>Total Obligations</Text>
          </View>
          <View style={styles.scoreBox}>
            <Text style={[styles.scoreValue, { color: "#059669" }]}>{data.completedObligations}</Text>
            <Text style={styles.scoreLabel}>Completed</Text>
          </View>
          <View style={styles.scoreBox}>
            <Text style={[styles.scoreValue, { color: "#DC2626" }]}>{data.overdueObligations}</Text>
            <Text style={styles.scoreLabel}>Overdue</Text>
          </View>
        </View>

        {data.riskLevel && (
          <Text style={styles.paragraph}>
            <Text style={{ fontWeight: 700 }}>Risk Level: </Text>
            {data.riskLevel}
          </Text>
        )}

        <Text style={styles.sectionTitle}>Summary</Text>
        <Text style={styles.paragraph}>{data.summary}</Text>

        <Text style={styles.sectionTitle}>Recommendations</Text>
        {data.recommendations.length > 0 ? (
          data.recommendations.map((rec, i) => (
            <View style={styles.bullet} key={i}>
              <Text style={styles.bulletDot}>{"\u2022"}</Text>
              <Text style={styles.bulletText}>{rec}</Text>
            </View>
          ))
        ) : (
          <Text style={styles.paragraph}>No outstanding recommendations at this time.</Text>
        )}

        <Text style={styles.footer}>
          Generated by RegulaSphere AI — Nexus SafeSphere Technologies Limited. This report is
          AI-assisted and should be reviewed by a qualified compliance consultant before
          submission to any regulator.
        </Text>
      </Page>
    </Document>
  );

  return renderToBuffer(doc);
}